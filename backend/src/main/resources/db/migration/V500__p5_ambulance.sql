-- ambulances.fareChart.rows[]: a hospital row picked from the list keeps its facilityId (ambfare.js destOf)
-- (+ upazilaId/district from the list, already columns)
ALTER TABLE ambulance_fare_rows ADD COLUMN facility_id TEXT;

-- ambulanceRequests.closedBy: 'auto' when an accepted trip was closed after 12 h (no rating then)
ALTER TABLE ambulance_requests ADD COLUMN closed_by TEXT CHECK (closed_by IN ('auto'));

-- fallback[] {id, name, phone, km, kmApprox}: kmApprox = the car has no base location (district centre)
ALTER TABLE ambreq_fallback ADD COLUMN km_approx BOOLEAN NOT NULL DEFAULT FALSE;

-- Firestore map/array insertion order (sentTo{} keys, calledIds[]) is part of what the apps show
ALTER TABLE ambreq_targets ADD COLUMN seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE ambreq_calls ADD COLUMN seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
